#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

// Reuse the locked desktop encoder; the README has no runtime dependencies.
const require = createRequire(
  new URL("../apps/desktop/package.json", import.meta.url),
);
const QRCode = require("qrcode");
const destination = "https://apps.apple.com/app/statusline/id6807851320";
const output = new URL(
  "../docs/assets/readme/app-store-qr.svg",
  import.meta.url,
);
const icon = await readFile(
  new URL("../branding/statusline-icon.svg", import.meta.url),
  "utf8",
);
const brand = JSON.parse(
  await readFile(new URL("../branding/logo.json", import.meta.url), "utf8"),
);
assert.match(
  icon,
  /viewBox="0 0 1024 1024"/,
  "Recheck the logo layout if its view box changes",
);

const qr = QRCode.create(destination, { errorCorrectionLevel: "H" });
const margin = 4;
const size = qr.modules.size;
const canvas = size + margin * 2;
const logoSize = 9;
const clearingSize = logoSize + 2;
const clearingStart = (size - clearingSize) / 2;
assert(Number.isInteger(clearingStart));
assert(clearingSize ** 2 / size ** 2 < 0.08, "Keep the central overlay small");

// Never cover finder, timing, alignment or other reserved QR modules.
for (let row = clearingStart; row < clearingStart + clearingSize; row += 1) {
  for (let col = clearingStart; col < clearingStart + clearingSize; col += 1) {
    assert(
      !qr.modules.isReserved(row, col),
      "The logo overlaps a reserved QR module",
    );
  }
}

const rows = [];
for (let row = 0; row < size; row += 1) {
  const runs = [];
  for (let col = 0; col < size; col += 1) {
    if (!qr.modules.get(row, col)) continue;
    const start = col;
    while (col + 1 < size && qr.modules.get(row, col + 1)) col += 1;
    const length = col - start + 1;
    runs.push(`M${start + margin} ${row + margin}h${length}v1h-${length}z`);
  }
  rows.push(`    <path d="${runs.join("")}" />`);
}

// Inline the canonical vectors, without external images, fonts or network calls.
const iconBody = icon
  .replace(/^<svg\b[^>]*>\s*/, "")
  .replace(/\s*<\/svg>\s*$/, "");
const logoStart = (canvas - logoSize) / 2;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="392" height="392" viewBox="0 0 ${canvas} ${canvas}" role="img" aria-labelledby="title description">
  <title id="title">Download Statusline for iPhone</title>
  <desc id="description">Public App Store download QR: ${destination}. Not a private device-pairing code.</desc>
  <!-- Generated by scripts/generate-download-qr.mjs. QR level H; four-module quiet zone. -->
  <rect width="${canvas}" height="${canvas}" fill="#FFFFFF" />
  <g fill="${brand.colors.canvas}" shape-rendering="crispEdges">
${rows.join("\n")}
  </g>
  <rect x="${clearingStart + margin}" y="${clearingStart + margin}" width="${clearingSize}" height="${clearingSize}" fill="#FFFFFF" />
  <svg x="${logoStart}" y="${logoStart}" width="${logoSize}" height="${logoSize}" viewBox="0 0 1024 1024">
${iconBody
  .split("\n")
  .map((line) => `    ${line}`)
  .join("\n")}
  </svg>
</svg>
`;

const args = process.argv.slice(2);
assert(
  args.length === 0 || (args.length === 1 && args[0] === "--check"),
  "Usage: node scripts/generate-download-qr.mjs [--check]",
);
if (args.includes("--check")) {
  assert.equal(
    await readFile(output, "utf8"),
    svg,
    "Download QR is stale; run node scripts/generate-download-qr.mjs",
  );
  console.log(
    `App Store QR is up to date (version ${qr.version}, level H, official logo).`,
  );
} else {
  await writeFile(output, svg);
  console.log(`Generated ${output.pathname} → ${destination}`);
}
