import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const catalog = JSON.parse(
  await readFile(path.join(root, "localization/messages.json"), "utf8"),
);
const entries = Object.entries(catalog).sort(([a], [b]) =>
  a.localeCompare(b, "en"),
);
const placeholders = (value) =>
  [...value.matchAll(/\{\d+\}/g)]
    .map(([match]) => match)
    .sort()
    .join(",");
for (const [key, translation] of entries) {
  if (!translation || placeholders(key) !== placeholders(translation)) {
    throw new Error(`Invalid translation or mismatched placeholders: ${key}`);
  }
}
const quote = (value) => JSON.stringify(value);
const kotlinQuote = (value) => quote(value).replaceAll("$", "\\$");
const outputs = new Map();
const widgetStrings = {
  app_name: "Statusline",
  widget_name: "Codex usage",
  widget_description: "See your remaining weekly quota and its next reset.",
  widget_weekly_limit_label: "WEEKLY LIMIT",
  widget_remaining_label: "REMAINING",
  widget_live_label: "LIVE",
  widget_no_data_label: "NO DATA",
  widget_resets_label: "RESETS",
  widget_connect_companion: "CONNECT COMPANION",
  widget_quota_number_placeholder: "53",
  widget_empty_quota_placeholder: "--",
  widget_percent_symbol: "%",
  widget_reset_time_placeholder: "09:02",
  widget_reset_date_placeholder: "02 SEP",
  widget_meter_scale_min: "0",
  widget_meter_scale_placeholder: "{0} LEFT",
  widget_meter_scale_max: "100",
};
const xml = (value) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll("'", "\\'");
for (const language of ["en", "es"]) {
  outputs.set(
    `apps/apple/Shared/${language}.lproj/Statusline.strings`,
    "/* Generated by scripts/generate-localizations.mjs. Do not edit. */\n" +
      entries
        .map(
          ([key, spanish]) =>
            `${quote(key)} = ${quote(language === "es" ? spanish : key)};`,
        )
        .join("\n") +
      "\n",
  );
  const camera =
    "Statusline uses the camera to scan the companion’s private pairing QR.";
  outputs.set(
    `apps/apple/statusline/${language}.lproj/InfoPlist.strings`,
    "/* Generated by scripts/generate-localizations.mjs. Do not edit. */\n" +
      `"NSCameraUsageDescription" = ${quote(language === "es" ? catalog[camera] : camera)};\n`,
  );
  outputs.set(
    `apps/android/app/src/main/res/values${language === "es" ? "-es" : ""}/strings.xml`,
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-localizations.mjs. Do not edit. -->\n<resources>\n' +
      Object.entries(widgetStrings)
        .map(([name, key]) => {
          const value = (
            language === "es" ? (catalog[key] ?? key) : key
          ).replace("{0}", "53");
          return `    <string name="${name}" formatted="false">${xml(value)}</string>`;
        })
        .join("\n") +
      "\n</resources>\n",
  );
}
outputs.set(
  "apps/android/app/src/main/java/inmerzion/statusline/localization/MessageCatalog.kt",
  "// Generated by scripts/generate-localizations.mjs. Do not edit.\n" +
    "package inmerzion.statusline.localization\n\n" +
    "internal object MessageCatalog {\n    val spanish: Map<String, String> = mapOf(\n" +
    entries
      .map(
        ([key, spanish]) =>
          `        ${kotlinQuote(key)} to ${kotlinQuote(spanish)},`,
      )
      .join("\n") +
    "\n    )\n}\n",
);
let stale = false;
for (const [relativePath, content] of outputs) {
  const target = path.join(root, relativePath);
  if (process.argv.includes("--check")) {
    const actual = await readFile(target, "utf8").catch(() => null);
    if (actual !== content) {
      console.error(`Outdated generated localization: ${relativePath}`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
if (stale) process.exitCode = 1;
else
  console.log(
    `Localization: ${entries.length} EN/ES messages; placeholders and ${outputs.size} generated files verified.`,
  );
